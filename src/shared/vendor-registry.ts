/** F2: one registry file on one mirror (null when that mirror lacks it). */
export function vendorMirrorUrl(cdn: CdnId, id: VendorId, file: string): string | null {
  const lib: VendorLib = VENDOR_LIBS[id]
  switch (cdn) {
    case 'jsdelivr': return `${VENDOR_CDN_PREFIX.jsdelivr}${lib.pkg}@${lib.version}/${file}`
    case 'unpkg': return `${VENDOR_CDN_PREFIX.unpkg}${lib.pkg}@${lib.version}/${file}`
    case 'zstatic': return `${VENDOR_CDN_PREFIX.zstatic}${lib.pkg}@${lib.version}/${file}`
    case 'npmmirror': return `${VENDOR_CDN_PREFIX.npmmirror}${lib.pkg}/${lib.version}/files/${file}`
    case 'staticfile': {
      const path = STATICFILE_PATHS[`${lib.pkg}@${lib.version}/${file}`]
      return path ? `${VENDOR_CDN_PREFIX.staticfile}${path}` : null
    }
  }
}

/** F2: sanitize a probe-derived mirror order. */
export function normalizeCdnOrder(value: unknown): CdnId[] {
  const raw = Array.isArray(value) ? value : typeof value === 'string' ? value.split(',') : []
  const out: CdnId[] = []
  for (const v of raw) if (typeof v === 'string' && (CDN_IDS as readonly string[]).includes(v) && !out.includes(v as CdnId)) out.push(v as CdnId)
  return out
}

/** jsDelivr URL of one registry file — preset-independent (runtime defaults, starters, export). */
export function vendorCdnUrl(id: VendorId, file: string): string {
  const lib: VendorLib = VENDOR_LIBS[id]
  return `${VENDOR_CDN_PREFIX.jsdelivr}${lib.pkg}@${lib.version}/${file}`
}

