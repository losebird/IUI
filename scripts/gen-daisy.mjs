// visual(①): bundle the daisyUI component CSS the ```iui-html sandbox inlines.
// Reads the installed daisyui package, keeps the components below, drops the
// responsive variant blocks (`sm:` … `2xl:` — the sandbox has no Tailwind) and
// writes src/themes/daisy.generated.ts. Run after bumping daisyui:
//   node scripts/gen-daisy.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(join(root, 'package.json'))
const dir = dirname(require.resolve('daisyui/package.json'))
const version = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).version

const BASE = ['properties', 'svg', 'rootcolor']
const COMPONENTS = [
  'alert', 'avatar', 'badge', 'breadcrumbs', 'button', 'card', 'checkbox', 'collapse', 'divider',
  'dropdown', 'fieldset', 'fileinput', 'filter', 'indicator', 'input', 'kbd', 'label', 'link', 'list',
  'loading', 'menu', 'mockup', 'modal', 'progress', 'radialprogress', 'radio', 'range', 'rating',
  'select', 'skeleton', 'stat', 'status', 'steps', 'swap', 'tab', 'table', 'textarea', 'timeline',
  'toast', 'toggle', 'tooltip', 'validator',
]
const UTILITIES = ['join', 'radius']
const THEMES = ['corporate', 'dim']

/** Remove `@media (width>=…){…}` blocks (responsive variants). */
function dropResponsive(css) {
  let out = ''
  let i = 0
  for (;;) {
    const j = css.indexOf('@media (width>=', i)
    if (j < 0) return out + css.slice(i)
    out += css.slice(i, j)
    let k = css.indexOf('{', j) + 1
    for (let depth = 1; depth > 0 && k < css.length; k++) {
      if (css[k] === '{') depth++
      else if (css[k] === '}') depth--
    }
    i = k
  }
}

// daisyUI's border-width token `--border` collides with the legacy IUI colour
// alias of the same name (old pages write `1px solid var(--border)`): rename it.
const read = (sub, name) => dropResponsive(readFileSync(join(dir, sub, `${name}.css`), 'utf8'))
  .replace(/\/\*![^*]*\*\/\s*/g, '')
  .replace(/--border(?=[:),\s])/g, '--border-w')
  .trim()

const css = [
  ...BASE.map((n) => read('base', n)),
  ...COMPONENTS.map((n) => read('components', n)),
  ...UTILITIES.map((n) => read('utilities', n)),
].join('\n')
const themes = THEMES.map((n) => read('theme', n).replace(/\s*\n\s*/g, '')).join('\n')

const lit = (s) => JSON.stringify(s)
writeFileSync(join(root, 'src/themes/daisy.generated.ts'), `// generated by scripts/gen-daisy.mjs — do not edit (daisyUI ${version}, MIT License)
export const DAISY_VERSION = ${lit(version)}
/** Components: ${COMPONENTS.join(', ')}; utilities: ${UTILITIES.join(', ')}. */
export const DAISY_CSS = ${lit(css)}
/** Built-in switchable themes: ${THEMES.join(', ')}. */
export const DAISY_THEMES_CSS = ${lit(themes)}
`)
console.log(`daisyUI ${version}: ${css.length} + ${themes.length} bytes`)
