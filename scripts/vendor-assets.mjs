// C6: copy pinned sandbox libraries from node_modules into lib/assets/vendor/<pkg>@<version>/...
// Run after tsdown (see package.json "build"). Fails loudly on version drift.
import { cpSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import vm from 'node:vm'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(join(root, 'package.json'))
const src = readFileSync(join(root, 'src/shared/vendor-registry.ts'), 'utf8')
// Parse VENDOR_LIBS without a TS loader: { pkg: '..', version: '..', js: '..', css: [..], extra: [..] }
const libs = [...src.matchAll(/\{\s*pkg:\s*'([^']+)',\s*version:\s*'([^']+)'([^}]*)\}/g)].map(([, pkg, version, rest]) => {
  const cdnOnly = /cdnJs:\s*'([^']+)'/.exec(rest)?.[1]
  // F1: every quoted string after pkg/version is a file or dir (gsap ships root-level `index.js`, `utils`).
  const files = [...rest.matchAll(/'([^']+)'/g)].map((m) => m[1]).filter((f) => f !== cdnOnly)
  return { pkg, version, files: [...new Set(files)] }
})
let bytes = 0
const pkgDirs = {}
for (const { pkg, version, files } of libs) {
  const pkgDir = require.resolve.paths(pkg).map((d) => join(d, pkg)).find((d) => existsSync(join(d, 'package.json')))
  if (!pkgDir) throw new Error(`vendor ${pkg}: not installed (add it to devDependencies)`)
  const installed = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version
  if (installed !== version) throw new Error(`vendor ${pkg}: registry pins ${version} but ${installed} is installed`)
  pkgDirs[pkg] = { dir: pkgDir, version }
  for (const f of files) {
    const from = join(pkgDir, f)
    if (!existsSync(from)) throw new Error(`vendor ${pkg}: missing ${f}`)
    const to = join(root, 'lib/assets/vendor', `${pkg}@${version}`, f)
    mkdirSync(dirname(to), { recursive: true })
    cpSync(from, to, { recursive: true })
    bytes += statSync(from).isDirectory() ? 0 : statSync(from).size
  }
}
// F1: same-origin ESM wrappers over the bundled UMD builds so `import * as d3 from 'd3'` /
// `import { Chart } from 'chart.js'` work offline (no esm.sh). Export names are taken from
// the very files being wrapped, so they cannot drift from the pinned versions.
function evalUmd(file) {
  const ctx = { console }
  ctx.globalThis = ctx
  ctx.self = ctx
  ctx.window = ctx
  vm.createContext(ctx)
  vm.runInContext(readFileSync(file, 'utf8'), ctx, { filename: file })
  return ctx
}
const esmNames = (code) => [...code.matchAll(/export \{([^}]*)\}/g)].flatMap((m) => m[1].split(',').map((x) => x.trim().split(/\s+as\s+/).pop()).filter(Boolean))
const ident = (n) => /^[A-Za-z_$][\w$]*$/.test(n) && n !== 'default'
const shimDir = join(root, 'lib/assets/vendor/iui-esm')
mkdirSync(shimDir, { recursive: true })
{
  const { dir, version } = pkgDirs.d3
  const names = Object.keys(evalUmd(join(dir, 'dist/d3.min.js')).d3).filter(ident).sort()
  if (names.length < 400) throw new Error(`vendor d3 shim: only ${names.length} exports found`)
  writeFileSync(join(shimDir, `d3@${version}.mjs`), `// generated by scripts/vendor-assets.mjs (d3@${version})\nimport '../d3@${version}/dist/d3.min.js'\nconst d3 = globalThis.d3\nexport default d3\nexport const { ${names.join(', ')} } = d3\n`)
}
{
  const { dir, version } = pkgDirs['chart.js']
  const Chart = evalUmd(join(dir, 'dist/chart.umd.js')).Chart
  const statics = new Set(Object.getOwnPropertyNames(Chart))
  const derived = new Set(['plugins', 'scales', 'registerables'])
  const names = esmNames(readFileSync(join(dir, 'dist/chart.js'), 'utf8')).filter(ident)
  const missing = names.filter((n) => !statics.has(n) && !derived.has(n))
  if (missing.length) throw new Error(`vendor chart.js shim: UMD lacks ${missing.join(', ')}`)
  const direct = names.filter((n) => statics.has(n) && n !== 'Chart')
  writeFileSync(join(shimDir, `chart.js@${version}.mjs`), [
    `// generated by scripts/vendor-assets.mjs (chart.js@${version}; the UMD build auto-registers everything)`,
    `import '../chart.js@${version}/dist/chart.umd.js'`,
    'const Chart = globalThis.Chart',
    'export default Chart',
    'export { Chart }',
    `export const { ${direct.join(', ')} } = Chart`,
    'export const plugins = { Colors: Chart.Colors, Decimation: Chart.Decimation, Filler: Chart.Filler, Legend: Chart.Legend, SubTitle: Chart.SubTitle, Title: Chart.Title, Tooltip: Chart.Tooltip }',
    'export const scales = { CategoryScale: Chart.CategoryScale, LinearScale: Chart.LinearScale, LogarithmicScale: Chart.LogarithmicScale, RadialLinearScale: Chart.RadialLinearScale, TimeScale: Chart.TimeScale, TimeSeriesScale: Chart.TimeSeriesScale }',
    'export const registerables = [Chart.controllers, Chart.elements, plugins, scales]',
    '',
  ].join('\n'))
  const helpers = esmNames(readFileSync(join(dir, 'dist/helpers.js'), 'utf8')).filter(ident)
  const lack = helpers.filter((n) => !(n in Chart.helpers))
  if (lack.length) throw new Error(`vendor chart.js helpers shim: UMD lacks ${lack.join(', ')}`)
  writeFileSync(join(shimDir, `chart.js@${version}-helpers.mjs`), `// generated by scripts/vendor-assets.mjs (chart.js@${version} helpers)\nimport '../chart.js@${version}/dist/chart.umd.js'\nexport const { ${helpers.join(', ')} } = globalThis.Chart.helpers\n`)
}
// R5-3b: CC0 models shipped with the plugin (assets/models → lib/assets/vendor/iui-models@N/).
const catalog = readFileSync(join(root, 'src/shared/model-catalog.ts'), 'utf8')
const modelDir = /BUNDLED_MODELS_DIR = '([^']+)'/.exec(catalog)?.[1]
const modelFiles = [...catalog.matchAll(/\bfile: '([^']+\.glb)'/g)].map((m) => m[1])
if (!modelDir || modelFiles.length < 8) throw new Error('vendor models: BUNDLED_MODELS not found in model-catalog.ts')
let modelBytes = 0
for (const f of modelFiles) {
  const from = join(root, 'assets/models', f)
  if (!existsSync(from)) throw new Error(`vendor models: missing assets/models/${f}`)
  const buf = readFileSync(from)
  if (buf.subarray(0, 4).toString('latin1') !== 'glTF') throw new Error(`vendor models: ${f} is not a GLB`)
  const to = join(root, 'lib/assets/vendor', modelDir, f)
  mkdirSync(dirname(to), { recursive: true })
  cpSync(from, to)
  modelBytes += buf.byteLength
}
console.log(`vendor-assets: ${libs.length} libs + 3 ESM shims + ${modelFiles.length} models (${(modelBytes / 1048576).toFixed(1)} MB), ${(bytes / 1048576).toFixed(1)} MB → lib/assets/vendor`)
