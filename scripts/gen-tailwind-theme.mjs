// visual(③): bundle Tailwind's default theme for the ```iui-html sandbox JIT
// (src/themes/tailwind-jit.ts). Reads the installed tailwindcss package and
// writes src/themes/tailwind-theme.generated.ts. Run after bumping tailwindcss:
//   node scripts/gen-tailwind-theme.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(join(root, 'package.json'))
const dir = dirname(require.resolve('tailwindcss/package.json'))
const version = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).version
const theme = readFileSync(join(dir, 'theme.css'), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\s*\n\s*/g, ' ')
  .replace(/\s{2,}/g, ' ')
  .trim()
const lit = (s) => JSON.stringify(s)
writeFileSync(join(root, 'src/themes/tailwind-theme.generated.ts'), `// generated by scripts/gen-tailwind-theme.mjs — do not edit (tailwindcss ${version}, MIT License)
export const TAILWIND_VERSION = ${lit(version)}
/** tailwindcss/theme.css (\`@theme default { … }\`). */
export const TAILWIND_THEME_CSS = ${lit(theme)}
`)
console.log(`tailwind theme ${version}: ${theme.length} chars`)
